export function localKey(country, region, county) {
  if (!country || !region || !county) return null;
  const c = String(county).trim().toUpperCase().replace(/[^A-Z0-9]+/g, '_');
  return `${String(country).toUpperCase()}-${String(region).toUpperCase()}-${c}`;
}

/** Prefer combinedAvg when estimateLocal is true and no county overlay. */
export function resolveUsRates(region, { county, estimateLocal = true } = {}) {
  const st = US_STATE_SALES_TAX[String(region || '').toUpperCase()];
  if (!st) return { state: null, local: null, mode: 'unknown' };
  const lk = localKey('US', region, county);
  if (lk && US_LOCAL_SAMPLES[lk]) {
    return { state: st, local: US_LOCAL_SAMPLES[lk], mode: 'state_plus_sample_local' };
  }
  if (estimateLocal && st.localHint && st.avgLocalRate > 0 && !county) {
    return {
      state: st,
      local: {
        rate: st.avgLocalRate,
        name: `${st.name} avg local (Tax Foundation pop-weighted)`,
        estimated: true,
      },
      mode: 'state_plus_avg_local',
    };
  }
  return { state: st, local: null, mode: 'state_only' };
}
